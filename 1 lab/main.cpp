#include <iostream>

#ifdef _WIN32
#include <windows.h>
#endif

#include "utils.h"
#include "task1.h"
#include "task2.h"
#include "task3.h"

int main() {
#ifdef _WIN32
    // Коректне відображення кирилиці у консолі Windows
    SetConsoleCP(CP_UTF8);
    SetConsoleOutputCP(CP_UTF8);
#endif

    ensureDataDir();   // усі файли зберігаються у підкаталозі data/

    while (true) {
        std::cout << "\n=========================================================\n"
                  << "  ЛАБОРАТОРНА РОБОТА №1   (варіант 11)\n"
                  << "  Файлові потоки C++. Масиви.\n"
                  << "=========================================================\n"
                  << "  1 - Завдання 1: перша половина * 2, друга * 3\n"
                  << "  2 - Завдання 2: останній мінімальний серед парних додатних\n"
                  << "  3 - Завдання 3: точки, що належать трикутнику ABC\n"
                  << "  0 - Вихід\n";

        int choice = readIntInRange("  Ваш вибір: ", 0, 3);
        switch (choice) {
            case 1: task1Menu(); break;
            case 2: task2Menu(); break;
            case 3: task3Menu(); break;
            case 0:
                std::cout << "\n  Роботу завершено.\n";
                return 0;
        }
    }
}
